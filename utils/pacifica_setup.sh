#!/bin/bash
##===- utils/pacifica_setup.sh - Setup mlir-aie env ----------*- Script -*-===##
# 
# This script sets up the environment to compile IRON designs in the pacifica
# simulation environment.
#
# The script will optionally download and set up mlir-aie
# 
# source pacifica_setup.sh [--force-install] <mlir-aie install dir> 
#
# Copyright (C) 2025, Advanced Micro Devices, Inc.
# SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
#
##===----------------------------------------------------------------------===##

FORCE_INSTALL=0
if [ "$1" == "--force-install" ]; then
  FORCE_INSTALL=1
  shift
fi


# install dir
if [ "$#" -ge 1 ]; then
    export MLIR_AIE_INSTALL_DIR=`realpath $1`
    FORCE_INSTALL=0
else
    export MLIR_AIE_INSTALL_DIR="$(pip show mlir_aie 2>/dev/null | grep ^Location: | awk '{print $2}')/mlir_aie"
fi


# If force install or an install dir isn't passed
if [[ $FORCE_INSTALL -eq 1 || ( "$#" -lt 1 && -z "$(pip show mlir_aie | grep ^Location:)" ) ]]; then
  
  # install mlir-aie wheel
  python3 -m pip install -I mlir_aie -f /group/xrlabs/jefff/pacifica-sim/latest-wheels
  export MLIR_AIE_INSTALL_DIR="$(pip show mlir_aie | grep ^Location: | awk '{print $2}')/mlir_aie"

  # install extras
  HOST_MLIR_PYTHON_PACKAGE_PREFIX=aie python3 -m pip install git+https://github.com/makslevental/mlir-python-extras@f08db06 -f https://github.com/llvm/eudsl/releases/expanded_assets/latest
  
  # these are needed for mesimulator
  python3 -m pip install toml bitstring
fi

# Write environment variables to pacifica_env.sh
cat > pacifica_env.sh <<EOF
# auto-generated by utils/pacifica_setup.sh

# setup environment for mlir-aie
export MLIR_AIE_DIR=${MLIR_AIE_INSTALL_DIR}
export PATH=${MLIR_AIE_INSTALL_DIR}/bin:\$PATH 
export PYTHONPATH=${MLIR_AIE_INSTALL_DIR}/python:\$PYTHONPATH
export PYTHONPATH=${MLIR_AIE_INSTALL_DIR}/aiebu/aiebu/share:\$PYTHONPATH
export LD_LIBRARY_PATH=${MLIR_AIE_INSTALL_DIR}/lib:\$LD_LIBRARY_PATH

# setup environment for simulator
if [[ $(hostname) == xco* ]]; then
  export PACIFICA_SIM_ROOT=/proj/rdi/staff/jefff/aie4/pacifica-sim
else
  export PACIFICA_SIM_ROOT=/group/xrlabs/jefff/pacifica-sim
fi
export CERVINO_ROOT=\$PACIFICA_SIM_ROOT/cervino
export ME_ROOT=\$PACIFICA_SIM_ROOT/cervino/aie4
export me_DIR=\$ME_ROOT/core_model/sipp/lib
export LD_LIBRARY_PATH=\$CERVINO_ROOT/ext/systemc/systemc-2.3.3/lib-linux64:\$LD_LIBRARY_PATH
export LD_LIBRARY_PATH=\$CERVINO_ROOT/ext/Boost_1_72_0/boost_1_72_0/rdi/lib/gcc8.3.0/lnx64.o:\$LD_LIBRARY_PATH
export PYTHONPATH=\$PYTHONPATH:\$ME_ROOT/python:\$ME_ROOT/applications

# setup environment for vitis
export VITIS=/proj/primebuilds/HEAD_INT_daily_latest/installs/lin64/HEAD/Vitis
export PATH=\${VITIS}/aietools/bin:\${VITIS}/bin:\$PATH
export XILINXD_LICENSE_FILE=/proj/xbuilds/licenses/:2100@aiengine4-eng
export LM_LICENSE_FILE=1757@xsjlicsrvip:2100@aiengine-eng

echo "PATH              : $PATH"
echo "LD_LIBRARY_PATH   : $LD_LIBRARY_PATH"
echo "PYTHONPATH        : $PYTHONPATH"
echo "PACIFICA_SIM_ROOT : $PACIFICA_SIM_ROOT"
echo "VITIS             : $VITIS"
EOF

echo "Generated pacifica_env.sh. To setup environment run:"
echo "source pacifica_env.sh"