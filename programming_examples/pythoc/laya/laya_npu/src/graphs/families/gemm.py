"""Decision GEMMs (device_00: K = 1024, device_01: K = 4096): C = A x W on 32 cores.

The topology is IRON's whole-array GEMM on NPU2: 4 core rows x 8 columns, 32x32x64
BF16 tiles with FP32 accumulation. A is split from four memtiles (one 32-row slice per
core row), W is forwarded per column, and each column's four 32x64 C tiles are joined
into one 128x64 object. Every core zeroes its accumulator, runs K/32 leaf MACs and
releases the tile; its repeat bound is the family's fixed 2 (the runtime sequence alone
decides how many tiles a core computes per dispatch).

The four projections of a transformer layer run on it (N = output width):

  qkv  K=1024 N=3072  C in tile64 layout   A rows 2*L*1024 apart per batch entry
  out  K=1024 N=1024  C flat               A rows   L*1024 apart
  fc1  K=1024 N=4096  C flat               A rows 2*L*1024 apart
  fc2  K=4096 N=1024  C flat               A rows   L*4096 apart

C is FP32 written into laya's ``packed`` operand (element i of the [L, N] value stream
goes to (i // 256) * 512 + i % 256; the other 256 words of every 512 are the bias half),
after the optional tile64 permutation ((r, j) -> (j // 64) * L * 64 + r * 64 + j % 64).
Batch entries sit 2 * L * N packed words apart.

Two sequence shapes exist (they were generated by different milestones):

* L >= 128 (``whole``): the whole-array sequence (row blocks of 128 tokens, ping-pong
  task groups of two row blocks), once per batch entry, with C remapped into the packed
  layout.
* L = 64 (``half``): a 128-row block is two 64-row halves (core rows 0-1 and 2-3). B = 1
  feeds both halves the same rows and drains them to the same addresses (repeat with
  stride 0); B >= 2 pairs batch entries 2s and 2s+1 into one block. At most four drains
  per shim channel between syncs; extra drains go into a second task group.

Everything is high-level IRON (ObjectFifo split/forward/join, Worker, Kernel, Runtime
fill/drain with TensorAccessPattern and TaskGroup); nothing drops to lower-level bindings.
"""

import numpy as np
from ml_dtypes import bfloat16

from aie.helpers.taplib import TensorAccessPattern
from aie.iron import Kernel, ObjectFifo, Program, Runtime, Worker
from aie.iron.controlflow import range_
from aie.iron.device import NPU2, Tile
from aie.iron.runtime.taskgroup import TaskGroup

ROWS, COLS = 4, 8            # core array
m, k, n = 32, 32, 64         # leaf tile
r, s, t = 8, 8, 8            # leaf micro block (L1 layouts)
BLOCK = m * ROWS             # tokens per row block
CORE_REPEAT = 2
QUEUE = 4                    # drains per shim channel between syncs (L = 64)

# projection -> (K, N, C layout, A pitch per batch entry in units of L * K)
PROJ = {
    "qkv": (1024, 3072, "tile64", 2),
    "out": (1024, 1024, "flat", 1),
    "fc1": (1024, 4096, "flat", 2),
    "fc2": (4096, 1024, "flat", 1),
}


def packed(i):
    """FP32 value index -> packed word (256 values per 512-word chunk)."""
    return (i // 256) * 512 + i % 256


def _dims(shape, dims):
    """A memtile-side stream walk given as (size, stride) pairs, outermost first."""
    return TensorAccessPattern(shape, 0, [d for d, _ in dims], [st for _, st in dims])


def topology(K):
    """Workers and the shim-side handles (A producers, B producers, C consumers)."""
    A_l2_ty = np.ndarray[(m * k,), np.dtype[bfloat16]]
    B_l2_ty = np.ndarray[(k * n,), np.dtype[bfloat16]]
    C_l2_ty = np.ndarray[(m * n * ROWS,), np.dtype[np.float32]]
    A_l1_ty = np.ndarray[(m, k), np.dtype[bfloat16]]
    B_l1_ty = np.ndarray[(k, n), np.dtype[bfloat16]]
    C_l1_ty = np.ndarray[(m, n), np.dtype[np.float32]]

    zero = Kernel("bf16_zero_kernel", "bf16_zero_kernel.o", [C_l1_ty])
    leaf = Kernel("laya_gemm_native", "laya_gemm_native.o", [A_l1_ty, B_l1_ty, C_l1_ty])

    # A: one memtile per core row (columns 0, 2, 4, 6), tiled to [m/r, k/s, r, s] in L1.
    A_l3l2, A_l2l1 = [], []
    for i in range(ROWS):
        f = ObjectFifo(A_l2_ty, name=f"A_L3L2_{i}", depth=2)
        A_l3l2.append(f)
        A_l2l1 += f.cons().split(
            [0], obj_types=[A_l1_ty], names=[f"A_L2L1_{i}"],
            to_stream=[_dims((m, k), [(m // r, r * k), (k // s, s), (r, k), (s, 1)])],
            tile=Tile(2 * i, 1))

    # B: forwarded down each column, tiled to [k/s, n/t, s, t].
    B_l3l2, B_l2l1 = [], []
    for col in range(COLS):
        f = ObjectFifo(B_l2_ty, name=f"B_L3L2_{col}", depth=2)
        B_l3l2.append(f)
        B_l2l1.append(f.cons().forward(
            obj_type=B_l1_ty, name=f"B_L2L1_{col}",
            to_stream=_dims((k, n), [(k // s, s * n), (n // t, t), (s, n), (t, 1)]), tile=Tile(col, 1)))

    # C: the column's four row tiles joined into one 128 x 64 row-major object.
    C_l2l3, C_l1l2 = [], [[None] * COLS for _ in range(ROWS)]
    for col in range(COLS):
        f = ObjectFifo(C_l2_ty, name=f"C_L2L3_{col}", depth=2,
                       to_stream=_dims((m, n), [(m // r, r * n), (r, t), (n // t, r * t), (t, 1)]))
        C_l2l3.append(f)
        parts = f.prod().join(
            [m * n * row for row in range(ROWS)], obj_types=[C_l1_ty] * ROWS,
            names=[f"C_L1L2_{col}_{row}" for row in range(ROWS)], depths=[1] * ROWS, tile=Tile(col, 1))
        for row in range(ROWS):
            C_l1l2[row][col] = parts[row]

    def core(in_a, in_b, out_c, zero_k, leaf_k):
        for _ in range_(CORE_REPEAT):
            acc = out_c.acquire(1)
            zero_k(acc)
            for _ in range_(K // k):
                a = in_a.acquire(1)
                b = in_b.acquire(1)
                leaf_k(a, b, acc)
                in_a.release(1)
                in_b.release(1)
            out_c.release(1)

    workers = [Worker(core, [A_l2l1[row].cons(), B_l2l1[col].cons(), C_l1l2[row][col].prod(), zero, leaf],
                      tile=Tile(col, 2 + row), stack_size=0xD00)
               for row in range(ROWS) for col in range(COLS)]
    shims = ([f.prod(tile=Tile(2 * i, 0)) for i, f in enumerate(A_l3l2)],
             [f.prod(tile=Tile(col, 0)) for col, f in enumerate(B_l3l2)],
             [f.cons(tile=Tile(col, 0)) for col, f in enumerate(C_l2l3)])
    return workers, shims


def tap(total, offset, sizes, strides):
    return TensorAccessPattern((total,), offset, sizes, strides)


def program(proj, L=128, B=1):
    K, N, layout, pitch = PROJ[proj]
    a_pitch, c_pitch = pitch * L * K, 2 * L * N
    a_len, w_len, c_len = (B - 1) * a_pitch + L * K, K * N, (B - 1) * c_pitch + 2 * L * N
    T = N // n // COLS                       # output tiles per core per row block
    KT = K // k
    workers, (A, W, C) = topology(K)

    def sequence(a, w, c, A, W, C):
        def a_fill(row, offset, tg):
            A[row].fill(a, tap=tap(a_len, offset, [T, KT, m, k], [0, k, K, 1]), group=tg)

        def b_fill(col, tg):
            W[col].fill(w, tap=tap(w_len, col * n, [T, KT, k, n], [COLS * n, k * N, N, 1]), group=tg)

        def whole(batch):
            """IRON's whole-array sequence over one batch entry, C remapped into the packed layout.

            A C drain covers up to two row blocks; the first such group shares its task group
            with the second (ping-pong), every later one closes its own."""
            blocks = L // BLOCK
            group_rows = min(2, blocks)
            tg = TaskGroup()
            for gi, base in enumerate(range(0, blocks, group_rows)):
                for col in range(COLS):
                    if layout == "tile64":   # tile j*8+col holds L*64 values; a row block 128*64 of them
                        off = packed(col * L * n + base * BLOCK * n)
                        sizes = [group_rows, T, BLOCK * n // 256, 256]
                        strides = [packed(BLOCK * n), packed(COLS * L * n), 512, 1]
                    else:
                        off = packed(base * BLOCK * N + col * n)
                        sizes, strides = [group_rows, T, BLOCK, n], [packed(BLOCK * N), packed(COLS * n), 2 * N, 1]
                    C[col].drain(c, tap=tap(c_len, batch * c_pitch + off, sizes, strides), wait=True, group=tg)
                    for rb in range(base, base + group_rows):
                        if col < ROWS:
                            a_fill(col, batch * a_pitch + (rb * ROWS + col) * m * K, tg)
                        b_fill(col, tg)
                if gi > 0:
                    tg.finish()
                    tg = TaskGroup()
            tg.finish()

        def half_drains(col, d0, d1):
            """(sizes, strides, offset) of one column's drains; the halves hold batch entries d0, d1."""
            hs, base = (d1 - d0) * c_pitch, d0 * c_pitch
            cols = [(col + COLS * j) * n for j in range(T)]
            if layout == "tile64":           # a 64-row tile is 16 packed chunks of 4 rows
                return [([2, L // 4, 4, n], [hs, 512, n, 1], base + packed((x // n) * L * n)) for x in cols]
            bases = [base + packed(x) for x in cols]
            if hs > 0 and len(bases) > 1:
                return [([len(bases), 2, L, n], [bases[1] - bases[0], hs, 2 * N, 1], bases[0])]
            return [([2, 1, L, n], [hs, 0, 2 * N, 1], b) for b in bases]

        def half():
            sections = [(0, 0)] if B == 1 else [(2 * i, 2 * i + 1) for i in range(B // 2)]
            for sec in sections:
                per_col = [half_drains(col, *sec) for col in range(COLS)]
                groups = max((len(d) + QUEUE - 1) // QUEUE for d in per_col)
                for g in range(groups):
                    tg = TaskGroup()
                    for col in range(COLS):
                        for sizes, strides, off in per_col[col][g * QUEUE:(g + 1) * QUEUE]:
                            C[col].drain(c, tap=tap(c_len, off, sizes, strides), wait=True, group=tg)
                    if g == 0:
                        for row in range(ROWS):
                            a_fill(row, sec[row // 2] * a_pitch + (row % 2) * m * K, tg)
                        for col in range(COLS):
                            b_fill(col, tg)
                    tg.finish()

        if L < BLOCK:
            half()
        else:
            for batch in range(B):
                whole(batch)

    rt = Runtime(sequence, [np.ndarray[(a_len,), np.dtype[bfloat16]], np.ndarray[(w_len,), np.dtype[bfloat16]],
                            np.ndarray[(c_len,), np.dtype[np.float32]], A, W, C])
    return str(Program(NPU2(), rt, workers=workers).resolve_program())


DEVICES = {"device_00": lambda: program("out"), "device_01": lambda: program("fc2")}

# laya_npu's names (M18 export order): per (L, B) bucket, twelve sequences of which
# these four (qkv, out, fc1, fc2) are consecutive, starting at 8.
_BUCKETS = [(L, B) for L in (64, 128, 256, 512) for B in (1, 2, 4, 8)]
_NAMES = {(L, B, p): f"sequence_{8 + 12 * i + j:03d}"
          for i, (L, B) in enumerate(_BUCKETS) for j, p in enumerate(PROJ)}
SEQUENCES = [(name, "exact", lambda p=p, L=L, B=B: program(p, L, B)) for (L, B, p), name in _NAMES.items()]
