"""Exercise actual C DMA chains with delayed S2MM and two core C buffers.

All cores produce in lockstep (stricter than W multicast requires). Acquiring
an S2MM lock and receiving its data are separate scheduler actions: a DMA can
hold a credit while stalled on its stream. No unbounded core lead is assumed.
Input is the NGS=1, CT=4, int8 fixture generated by check_c_reassembly.lit
(M=512, N=768, K=128, three columns); each row slice is 4096 i32 words.
"""

import random
import sys
from aie.dialects import aie, aiex
from aie.extras.context import mlir_mod_ctx
from aie.ir import MemRefType, Module


def extract(module):
    ops = list(list(module.body.operations)[0].regions[0].blocks[0].operations)
    locks = {
        op.results[0]: op.attributes["init"].value
        for op in ops
        if op.name == "aie.lock"
    }
    dma = next(op for op in ops if op.name == "aie.memtile_dma")
    blocks = list(dma.regions[0].blocks)
    bds, starts = {}, {}
    for block in blocks:
        for op in block.operations:
            if op.name == "aie.dma_start":
                ch = op.attributes["channel_index"].value
                direction = (
                    "S2MM" if op.attributes["channel_dir"].value == 0 else "MM2S"
                )
                if (direction == "S2MM" and ch in range(2, 6)) or (
                    direction == "MM2S" and ch == 7
                ):
                    starts[ch if direction == "S2MM" else 7] = blocks.index(
                        op.successors[0]
                    )
        bd = next((o for o in block.operations if o.name == "aie.dma_bd"), None)
        if bd is None:
            continue
        lock_ops = [o for o in block.operations if o.name == "aie.use_lock"]
        assert [o.attributes["action"].value for o in lock_ops] == [
            int(aie.LockAction.AcquireGreaterEqual),
            int(aie.LockAction.Release),
        ]
        acq, rel = [
            (o.operands[0], o.operands[1].owner.attributes["value"].value)
            for o in lock_ops
        ]
        next_bd = next(o for o in block.operations if o.name == "aie.next_bd")
        offset = (
            bd.attributes["static_offset"].value
            if "static_offset" in bd.attributes
            else 0
        )
        length = (
            bd.attributes["static_len"].value
            if "static_len" in bd.attributes
            else MemRefType(bd.operands[0].type).shape[0]
        )
        bds[blocks.index(block)] = (
            acq,
            rel,
            bd.operands[0],
            offset,
            length,
            blocks.index(next_bd.successors[0]),
        )
    assert len(starts) == 5, starts
    return locks, starts, bds


def simulate(program, seed=None):
    locks, starts, bds = program
    locks, pcs = locks.copy(), starts.copy()
    acquired = {ch: False for ch in pcs}
    ready = [[] for _ in range(4)]
    produced = 0
    limit = 12
    memory = {}
    output = []
    # NGS=1, CT=4: each C buffer is one 4096-word row slice.
    row_words = 4096
    rng = random.Random(seed)
    for _ in range(10000):
        choices = ["core", 2, 3, 4, 5, 7]
        if seed is not None:
            rng.shuffle(choices)
        # Prioritize rows 0..2 over row 3 and drains to check that fast
        # producers cannot consume a delayed producer's buffer credits.
        progress = False
        for ch in choices:
            if ch == "core":
                if produced == limit or any(len(q) == 2 for q in ready):
                    continue
                for q in ready:
                    q.append(produced)
                produced += 1
                progress = True
                break
            acq, rel, buf, offset, length, nxt = bds[pcs[ch]]
            if not acquired[ch]:
                if locks[acq[0]] < acq[1]:
                    continue
                locks[acq[0]] -= acq[1]
                acquired[ch] = True
                progress = True
                break
            if ch != 7:
                row = ch - 2
                if not ready[row]:
                    continue
                assert length == row_words and offset == row * row_words
                key = (buf, row)
                assert key not in memory, "overwrote an undrained row"
                memory[key] = (ready[row].pop(0), row)
            else:
                assert offset % row_words == length % row_words == 0
                for row in range(offset // row_words, (offset + length) // row_words):
                    assert (buf, row) in memory, "drained an unwritten row"
                    output.append(memory.pop((buf, row)))
                    i = len(output) - 1
                    assert output[-1] == (i // 4, i % 4), "incorrect output order"
            locks[rel[0]] += rel[1]
            pcs[ch] = nxt
            acquired[ch] = False
            progress = True
            break
        if len(output) == limit * 4:
            return
        assert (
            progress
        ), f"deadlock after {produced} lockstep core outputs; drained {len(output)} rows"
    raise AssertionError("schedule did not complete")


with mlir_mod_ctx():
    module = Module.parse(open(sys.argv[1]).read())
    program = extract(module)
    simulate(program)
    for seed in range(100):
        simulate(program, seed)
    print(
        "PASS: delayed-row schedule and 100 randomized schedules preserve ownership/order and complete"
    )
